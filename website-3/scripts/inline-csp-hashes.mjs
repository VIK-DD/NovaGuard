// Collect the SHA-256 of every inline <script> and <style> the build produced,
// so the Worker can name them in the Content-Security-Policy instead of
// nonce-ing whatever it finds.
//
// The nonce it replaced was applied by pattern: an HTMLRewriter stamped the
// response nonce onto every script and style element on the way out, which
// permits any script that reached the HTML before the rewriter ran - including
// one that got there by accident. A nonce says "the server put this here"; the
// server was not actually checking. A hash says "this exact code", which no
// injected script can satisfy.
//
// Runs after `astro build`. The set is small because most of these are the same
// few scripts repeated across pages - the theme pre-paint, the status poller -
// so deduplicating leaves a couple of dozen hashes and a CSP header under 2 KB.

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DIST = join(ROOT, "dist");
const OUTPUT = join(ROOT, "worker", "inline-hashes.js");

// Only elements with no src/href are inline; the rest are covered by 'self'.
const ELEMENT = /<(script|style)\b([^>]*)>([\s\S]*?)<\/\1\s*>/gi;
const HAS_SOURCE = /\s(?:src|href)\s*=/i;

async function htmlFiles(directory) {
  const found = [];
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch {
    return found;
  }
  for (const entry of entries) {
    const full = join(directory, entry.name);
    if (entry.isDirectory()) found.push(...(await htmlFiles(full)));
    else if (entry.name.endsWith(".html")) found.push(full);
  }
  return found;
}

function sha256(body) {
  return `sha256-${createHash("sha256").update(body, "utf8").digest("base64")}`;
}

export async function collectInlineHashes(directory = DIST) {
  const script = new Set();
  const style = new Set();
  const files = await htmlFiles(directory);

  for (const file of files) {
    const html = await readFile(file, "utf8");
    for (const [, tag, attributes, body] of html.matchAll(ELEMENT)) {
      if (HAS_SOURCE.test(attributes)) continue;
      // An empty inline element needs no permission and hashing "" would add a
      // source that matches every empty script anywhere.
      if (!body) continue;
      (tag.toLowerCase() === "script" ? script : style).add(sha256(body));
    }
  }

  return {
    script: [...script].sort(),
    style: [...style].sort(),
    pages: files.length,
  };
}

async function main() {
  const { script, style, pages } = await collectInlineHashes();

  if (pages === 0) {
    throw new Error(
      `No built pages found in ${relative(ROOT, DIST)}. Run this after astro build.`,
    );
  }
  if (script.length === 0 && style.length === 0) {
    // Every build so far inlines the theme pre-paint script and Astro's CSS.
    // Zero would mean the scan stopped matching, and shipping that silently
    // hands the Worker an empty allow-list.
    throw new Error("Found no inline scripts or styles - the scan is probably broken.");
  }

  const file = `// GENERATED by scripts/inline-csp-hashes.mjs - do not edit by hand.
//
// SHA-256 of every inline <script> and <style> in the build, named directly in
// the Content-Security-Policy. Regenerated by \`npm run build\`; a stale copy
// here would block the site's own inline code, so never hand-edit it.
//
// ${pages} page(s) scanned.

export const INLINE_SCRIPT_HASHES = ${JSON.stringify(script, null, 2)};

export const INLINE_STYLE_HASHES = ${JSON.stringify(style, null, 2)};
`;

  await writeFile(OUTPUT, file, "utf8");
  console.log(
    `inline-csp-hashes: ${script.length} script + ${style.length} style hashes ` +
      `from ${pages} page(s) → ${relative(ROOT, OUTPUT)}`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await main();
}
